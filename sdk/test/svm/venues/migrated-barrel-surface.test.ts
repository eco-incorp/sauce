describe("migrated venue barrel surface", () => {
  it("pins the expected count (401) so a future edit is a deliberate, reviewed change", () => {
    expect(MIGRATED_VALUE_EXPORTS.length).toBe(401);
  });

  it("every migrated value-level export actually resolves through the @eco-incorp/sauce/svm barrel", () => {
    // A name silently dropped by an ambiguous `export *` (or a typo'd alias)
    // reads as `undefined` here — this is the exact regression class an
    // explicit named re-export block exists to prevent. Note two DIFFERENT
    // names legitimately resolving to the SAME underlying value is not a bug
    // to catch: e.g. `pancakeswapClmmRaydiumSqrtPriceAtTick` and
    // `stabbleClmmRaydiumSqrtPriceAtTick` both alias raydium-clmm's own
    // `raydiumSqrtPriceAtTick` (both families are raydium-clmm clones), by
    // design, same as any two consumers importing one shared helper.
    const missing = MIGRATED_VALUE_EXPORTS.filter(
      (name) => (svm as Record<string, unknown>)[name] === undefined,
    );
    expect(missing).toEqual([]);
  });
});
