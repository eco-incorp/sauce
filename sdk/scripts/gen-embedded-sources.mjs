#!/usr/bin/env node
// Embeds the non-TypeScript files the SDK reads at run time into TypeScript modules, so the SDK
// has one code path in Node and in a browser: nothing it ships reads the filesystem.
//
//   src/embedded/sources.generated.ts   the SauceScript standard library (`src/std/**`), the recipe
//                                       programs (`src/recipes/*.sauce.ts`) and every protocol
//                                       ABI twin (`src/protocols/<slug>/<Export>.json`)
//   src/embedded/skills.generated.ts    the protocol skill documents (`src/skills/*.md`)
//
// Both are BUILD OUTPUT, not source: gitignored, regenerated by `build`, `typecheck`,
// `typecheck:test` and `test`, and never edited by hand. The files they copy stay where they are
// and remain the source of truth; `--check` exits non-zero when a generated module no longer
// matches them, which `test/embedded-sources.test.ts` runs.
//
// JSON is embedded minified (`JSON.stringify(JSON.parse(text))`, key order preserved) — the compiler
// parses what it is served, so whitespace cannot reach a program's bytes. Source text is embedded
// verbatim, because `settleSource()` and friends return it as the program a partner reads and hashes.
import { existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

const SDK = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = join(SDK, "src");
const OUT_DIR = join(SRC, "embedded");

/** Every file under `dir`, as `/`-separated paths relative to `dir`, sorted. */
function walk(dir) {
  const out = [];
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) {
      for (const child of walk(full)) out.push(`${name}/${child}`);
    } else {
      out.push(name);
    }
  }

  return out.sort();
}

const posix = (path) => path.split(sep).join("/");
const read = (path) => readFileSync(path, "utf8");
const minifyJson = (path) => JSON.stringify(JSON.parse(read(path)));

function stdSources() {
  const root = join(SRC, "std");

  return walk(root).map((path) => {
    const full = join(root, path);

    return [path, path.endsWith(".json") ? minifyJson(full) : read(full)];
  });
}

// The EVM recipes only: the SVM settle program is GENERATED by `svmSettleSource(n)`, and its
// checked-in N=1 file is an asset for readers, not something the SDK reads.
function recipeSources() {
  const dir = join(SRC, "recipes");

  return readdirSync(dir)
    .filter((name) => name.endsWith(".sauce.ts"))
    .sort()
    .map((name) => [posix(relative(SRC, join(dir, name))), read(join(dir, name))]);
}

function protocolAbis() {
  const root = join(SRC, "protocols");

  return readdirSync(root)
    .sort()
    .flatMap((slug) => {
      const dir = join(root, slug);
      if (!statSync(dir).isDirectory()) return [];

      return readdirSync(dir)
        .filter((name) => name.endsWith(".json"))
        .sort()
        .map((name) => [`${slug}/${name}`, minifyJson(join(dir, name))]);
    });
}

function skillDocuments() {
  const root = join(SRC, "skills");

  return readdirSync(root)
    .filter((name) => name.endsWith(".md"))
    .sort()
    .map((name) => [name.slice(0, -".md".length), read(join(root, name))]);
}

function record(name, doc, entries) {
  const body = entries.map(([key, value]) => `  ${JSON.stringify(key)}: ${JSON.stringify(value)},`);

  return [
    `/** ${doc} */`,
    `export const ${name}: Readonly<Record<string, string>> = {`,
    ...body,
    "};",
  ];
}

function module(from, blocks) {
  return [
    "// GENERATED by sdk/scripts/gen-embedded-sources.mjs. Do not edit: it is build output",
    "// (gitignored), rewritten by `build`, `typecheck` and `test`. Edit the files it copies:",
    `// ${from}.`,
    "",
    ...blocks.flatMap((block) => [...block, ""]),
  ].join("\n");
}

const OUTPUTS = {
  "sources.generated.ts": () =>
    module("src/std, src/recipes/*.sauce.ts and src/protocols/*/*.json", [
      record(
        "STD_SOURCES",
        "`src/std/**`, keyed by path under `std/` — the SauceScript standard library.",
        stdSources(),
      ),
      record(
        "RECIPE_SOURCES",
        "Each shipped `.sauce.ts` recipe, keyed by path under `src/`, verbatim.",
        recipeSources(),
      ),
      record(
        "PROTOCOL_ABIS",
        "Every protocol ABI twin, keyed `<slug>/<Export>.json`, minified.",
        protocolAbis(),
      ),
    ]),
  "skills.generated.ts": () =>
    module("src/skills/*.md", [
      record(
        "SKILL_DOCUMENTS",
        "Each `src/skills/*.md`, keyed by file name without `.md`.",
        skillDocuments(),
      ),
    ]),
};

const check = process.argv.includes("--check");
const stale = [];

for (const [name, render] of Object.entries(OUTPUTS)) {
  const path = join(OUT_DIR, name);
  const text = render();
  const current = existsSync(path) ? read(path) : undefined;
  if (current === text) continue;
  if (check) {
    stale.push(posix(relative(SDK, path)));
    continue;
  }
  mkdirSync(OUT_DIR, { recursive: true });
  writeFileSync(path, text);
}

if (stale.length > 0) {
  console.error(
    `gen-embedded-sources: stale or missing ${stale.join(", ")} — run \`node scripts/gen-embedded-sources.mjs\`.`,
  );
  process.exit(1);
}
