#!/usr/bin/env node
// Embeds the non-TypeScript files the SDK reads at run time into TypeScript modules, so the SDK
// has one code path in Node and in a browser: nothing it ships reads the filesystem.
//
//   src/embedded/sources.generated.ts   the SauceScript standard library (`src/std/**`), the recipe
//                                       programs (`src/recipes/*.sauce.ts`) and every protocol
//                                       ABI twin (`src/protocols/<slug>/<Export>.json`)
//   src/embedded/skills.generated.ts    the per-protocol documents, which are the `sauce-protocols`
//                                       agent skill's references (`skills/sauce-protocols/references/*.md`
//                                       at the repository root)
//   src/embedded/sdk-releases.generated.ts
//                                       every released SDK and the releases it pinned, from the
//                                       "Which versions work together" table of `docs/changelog.md`
//                                       (`scripts/lib/sdk-releases.mjs`, which validates it), which
//                                       a refusal of a Pot names
//
// They are BUILD OUTPUT, not source: gitignored, regenerated by `build`, `typecheck`,
// `typecheck:test` and `test`, and never edited by hand. The files they copy stay where they are
// and remain the source of truth; `--check` exits non-zero when a generated module no longer
// matches them, which `test/embedded-sources.test.ts` runs.
//
// JSON is embedded minified (`JSON.stringify(JSON.parse(text))`, key order preserved) — the compiler
// parses what it is served, so whitespace cannot reach a program's bytes. Source text is embedded
// verbatim, because `settleSource()` and friends return it as the program a partner reads and hashes.
import { existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

import { sdkReleasesOf } from "./lib/sdk-releases.mjs";
import {
  compileInstalledCompilerProbe,
  readInstalledCompilerProvenance,
} from "./lib/compiler-provenance.mjs";

const SDK = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = join(SDK, "src");
// The per-protocol documents live once, in the agent skill that ships them; `/skills` serves the
// same files, so what an agent reads and what `getProtocolSkill` returns cannot differ.
const PROTOCOL_DOCUMENTS = join(SDK, "..", "skills", "sauce-protocols", "references");
// The version table the release process keeps, and `docs:check` holds to `releases.json`.
const CHANGELOG = join(SDK, "..", "docs", "changelog.md");
const OUT_DIR = join(SRC, "embedded");

/** Every file under `dir`, as `/`-separated paths relative to `dir`, sorted. */
function walk(dir) {
  const out = [];
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) {
      for (const child of walk(full)) out.push(`${name}/${child}`);
    } else {
      out.push(name);
    }
  }

  return out.sort();
}

const posix = (path) => path.split(sep).join("/");
const read = (path) => readFileSync(path, "utf8");
const minifyJson = (path) => JSON.stringify(JSON.parse(read(path)));

function stdSources() {
  const root = join(SRC, "std");

  return walk(root).map((path) => {
    const full = join(root, path);

    return [path, path.endsWith(".json") ? minifyJson(full) : read(full)];
  });
}

// The EVM recipes only: the SVM settle program is GENERATED by `svmSettleSource(n)`, and its
// checked-in N=1 file is an asset for readers, not something the SDK reads.
function recipeSources() {
  const dir = join(SRC, "recipes");

  return readdirSync(dir)
    .filter((name) => name.endsWith(".sauce.ts"))
    .sort()
    .map((name) => [posix(relative(SRC, join(dir, name))), read(join(dir, name))]);
}

function protocolAbis() {
  const root = join(SRC, "protocols");

  return readdirSync(root)
    .sort()
    .flatMap((slug) => {
      const dir = join(root, slug);
      if (!statSync(dir).isDirectory()) return [];

      return readdirSync(dir)
        .filter((name) => name.endsWith(".json"))
        .sort()
        .map((name) => [`${slug}/${name}`, minifyJson(join(dir, name))]);
    });
}

function skillDocuments() {
  const root = PROTOCOL_DOCUMENTS;

  return readdirSync(root)
    .filter((name) => name.endsWith(".md"))
    .sort()
    .map((name) => [name.slice(0, -".md".length), read(join(root, name))]);
}

function record(name, doc, entries) {
  const body = entries.map(([key, value]) => `  ${JSON.stringify(key)}: ${JSON.stringify(value)},`);

  return [
    `/** ${doc} */`,
    `export const ${name}: Readonly<Record<string, string>> = {`,
    ...body,
    "};",
  ];
}

function module(from, blocks) {
  return [
    "// GENERATED by sdk/scripts/gen-embedded-sources.mjs. Do not edit: it is build output",
    "// (gitignored), rewritten by `build`, `typecheck` and `test`. Edit the files it copies:",
    `// ${from}.`,
    "",
    ...blocks.flatMap((block) => [...block, ""]),
  ].join("\n");
}

const recordCompiler = process.argv.includes("--record-compiler-probe");
if (recordCompiler && process.argv.includes("--check")) {
  throw new Error("--record-compiler-probe cannot be combined with --check");
}
const actualProbe = recordCompiler ? compileInstalledCompilerProbe() : undefined;
const compilerProvenance =
  actualProbe === undefined
    ? readInstalledCompilerProvenance()
    : {
        compiler: actualProbe.compiler,
        wasmSha256: actualProbe.wasmSha256,
      };
const releaseTablePath = join(SRC, "deployments/releases.json");
const releaseTable = JSON.parse(read(releaseTablePath));
if (actualProbe !== undefined) {
  const descriptor = { compilerWasmSha256: actualProbe.wasmSha256, program: actualProbe.program };
  const previous = releaseTable.compilerProvenance?.[actualProbe.compiler];
  if (
    previous !== undefined &&
    (previous.compilerWasmSha256 !== descriptor.compilerWasmSha256 ||
      previous.program !== descriptor.program)
  ) {
    throw new Error(
      `compiler ${actualProbe.compiler} already has different immutable WASM/probe provenance`,
    );
  }
  if (previous === undefined) {
    releaseTable.compilerProvenance = {
      ...releaseTable.compilerProvenance,
      [actualProbe.compiler]: descriptor,
    };
    writeFileSync(releaseTablePath, `${JSON.stringify(releaseTable, null, 2)}\n`);
  }
}
const compilerProbes = releaseTable.compilerProvenance;
if (
  compilerProbes === null ||
  typeof compilerProbes !== "object" ||
  Array.isArray(compilerProbes)
) {
  throw new Error(
    "Missing trusted compiler provenance: run gen-embedded-sources.mjs --record-compiler-probe",
  );
}
for (const [version, descriptor] of Object.entries(compilerProbes)) {
  if (
    !version ||
    !/^[0-9a-f]{64}$/.test(descriptor.compilerWasmSha256) ||
    !/^0x(?:[0-9a-fA-F]{2})+$/.test(descriptor.program) ||
    descriptor.program.length > 2050
  ) {
    throw new Error(`Malformed retained compiler provenance for ${version}`);
  }
}
if (
  compilerProbes[compilerProvenance.compiler]?.compilerWasmSha256 !== compilerProvenance.wasmSha256
) {
  throw new Error(
    `Installed compiler ${compilerProvenance.compiler} needs matching retained WASM/probe provenance; run gen-embedded-sources.mjs --record-compiler-probe`,
  );
}

const OUTPUTS = {
  "compiler.generated.ts": () =>
    module("the installed sauce-compiler package and its actual Node/browser WASM bytes", [
      [
        "/** Actual build-time compiler artifact identity; browser consumers need no filesystem access. */",
        `export const COMPILER_PROVENANCE = ${JSON.stringify(compilerProvenance)} as const;`,
        "/** Immutable compiler-produced known-answer descriptors, retained across SDK upgrades. */",
        "export const COMPILER_COMPATIBILITY_PROBES: Readonly<Record<string, { readonly compilerWasmSha256: string; readonly program: `0x${string}` }>> = " +
          JSON.stringify(compilerProbes) +
          ";",
      ],
    ]),
  "sources.generated.ts": () =>
    module("src/std, src/recipes/*.sauce.ts and src/protocols/*/*.json", [
      record(
        "STD_SOURCES",
        "`src/std/**`, keyed by path under `std/` — the SauceScript standard library.",
        stdSources(),
      ),
      record(
        "RECIPE_SOURCES",
        "Each shipped `.sauce.ts` recipe, keyed by path under `src/`, verbatim.",
        recipeSources(),
      ),
      record(
        "PROTOCOL_ABIS",
        "Every protocol ABI twin, keyed `<slug>/<Export>.json`, minified.",
        protocolAbis(),
      ),
    ]),
  "skills.generated.ts": () =>
    module("skills/sauce-protocols/references/*.md", [
      record(
        "SKILL_DOCUMENTS",
        "Each `skills/sauce-protocols/references/*.md`, keyed by file name without `.md`.",
        skillDocuments(),
      ),
    ]),
  "sdk-releases.generated.ts": () =>
    module('docs/changelog.md (its "Which versions work together" table)', [
      [
        "/** Every released SDK and the releases it pinned, in the changelog's order: each row keyed by its",
        " *  column's name lowercased, every version as the table gives it (`scripts/lib/sdk-releases.mjs`). */",
        "export const SDK_RELEASES: ReadonlyArray<Readonly<Record<string, string>>> = [",
        ...sdkReleasesOf(read(CHANGELOG)).map((release) => `  ${JSON.stringify(release)},`),
        "];",
      ],
    ]),
};

const check = process.argv.includes("--check");
const stale = [];

for (const [name, render] of Object.entries(OUTPUTS)) {
  const path = join(OUT_DIR, name);
  const text = render();
  const current = existsSync(path) ? read(path) : undefined;
  if (current === text) continue;
  if (check) {
    stale.push(posix(relative(SDK, path)));
    continue;
  }
  mkdirSync(OUT_DIR, { recursive: true });
  writeFileSync(path, text);
}

if (stale.length > 0) {
  console.error(
    `gen-embedded-sources: stale or missing ${stale.join(", ")} — run \`node scripts/gen-embedded-sources.mjs\`.`,
  );
  process.exit(1);
}
